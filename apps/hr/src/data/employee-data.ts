export type LeaveStatus = "Available" | "Pending";
export type LeaveUnit = "days" | "hours";

// PROFILE DUMMY
export interface EmployeeRecord {
  id: string;
  name: string;
  title: string;
  department: string;
  status: string;
  hireDate: string;
  workPhone: string;
  workEmail: string;
  officeLocation: string;
  avatar: string;
}

export interface LeaveBase {
  id: number;
  name: string;
  status: LeaveStatus;
  unit: LeaveUnit;
}

export interface LeaveWithBalance extends LeaveBase {
  available: number;
  pending: number;
  estimated: number;
}

export interface LeaveWithRequest extends LeaveBase {
  leaveFrom: string;
  leaveTo: string;
  pending: number;
  type: string;
}

export type LeaveRecord = LeaveWithBalance | LeaveWithRequest;

export interface EmployeeLeaveData {
  employee: EmployeeRecord;
  leave: LeaveRecord[];
}

